"""Generate `lib/FirelinkCore/src/Cp932Table.inc`: Windows code page 932 (Shift-JIS) <-> UTF-16 lookup tables.

Why this exists: on Windows, `Encodings.cpp` uses `MultiByteToWideChar` / `WideCharToMultiByte` with code page 932. Other
platforms have no such API, and `iconv` is not guaranteed to be usable (its gconv modules are missing from some minimal
containers/sandboxes). Python's `cp932` codec implements the same Microsoft variant of Shift-JIS, so we freeze its
tables into a self-contained C++ include. The output is committed; re-run this script only to regenerate it:

    python tools/gen_cp932_table.py > lib/FirelinkCore/src/Cp932Table.inc

Tables produced:
  * CP932_DOUBLE_BYTE_DECODE: dense [lead][trail] -> UTF-16 code unit (0 = unmapped), leads 0x81-0x9F and 0xE0-0xFC,
    trails 0x40-0xFC.
  * CP932_ENCODE: (UTF-16 code unit, CP932 code) pairs sorted by code unit, for binary search. Codes <= 0xFF are single
    bytes (half-width katakana etc.); larger codes are (lead << 8 | trail).
"""

import sys

LEAD_RANGES = [(0x81, 0x9F), (0xE0, 0xFC)]
TRAIL_MIN, TRAIL_MAX = 0x40, 0xFC
TRAIL_COUNT = TRAIL_MAX - TRAIL_MIN + 1  # 189


def lead_bytes() -> list[int]:
    return [b for lo, hi in LEAD_RANGES for b in range(lo, hi + 1)]


def main() -> int:
    leads = lead_bytes()

    decode: list[int] = []
    for lead in leads:
        for trail in range(TRAIL_MIN, TRAIL_MAX + 1):
            try:
                s = bytes([lead, trail]).decode("cp932")
            except UnicodeDecodeError:
                decode.append(0)
                continue
            # Only BMP, single-code-unit results are representable in this table.
            decode.append(ord(s) if len(s) == 1 and ord(s) <= 0xFFFF else 0)

    encode: dict[int, int] = {}
    for cp in range(0x80, 0x10000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        try:
            b = chr(cp).encode("cp932")
        except UnicodeEncodeError:
            continue
        encode[cp] = b[0] if len(b) == 1 else (b[0] << 8) | b[1]

    # Deliberate deviation from Python: Microsoft's code page 932 table maps byte 0xA0 to U+00A0 (NO-BREAK SPACE), which
    # is what `MultiByteToWideChar(932, ...)` returned in the original Windows implementation. Python maps 0xA0 to
    # U+F8F0 instead. `Encodings.cpp` decodes 0xA0 -> U+00A0, so add the reverse path to keep byte round-trips exact.
    # (U+F8F0 -> 0xA0 from Python's table is kept; it is harmless.)
    encode[0x00A0] = 0xA0

    print("// GENERATED by tools/gen_cp932_table.py -- do not edit by hand.")
    print("// Windows code page 932 (Microsoft Shift-JIS) <-> UTF-16, frozen from Python's `cp932` codec.")
    print()
    print(f"constexpr int CP932_TRAIL_MIN = 0x{TRAIL_MIN:02X};")
    print(f"constexpr int CP932_TRAIL_COUNT = {TRAIL_COUNT};")
    print(f"constexpr int CP932_LEAD_COUNT = {len(leads)};")
    print()
    print("// Map lead byte -> row index, or -1 if not a double-byte lead.")
    row_of = {lead: i for i, lead in enumerate(leads)}
    print("constexpr signed char CP932_LEAD_ROW[256] = {")
    for base in range(0, 256, 16):
        print("    " + ", ".join(str(row_of.get(b, -1)) for b in range(base, base + 16)) + ",")
    print("};")
    print()
    print(f"constexpr char16_t CP932_DOUBLE_BYTE_DECODE[{len(decode)}] = {{")
    for i in range(0, len(decode), 12):
        print("    " + ", ".join(f"0x{v:04X}" for v in decode[i:i + 12]) + ",")
    print("};")
    print()
    items = sorted(encode.items())
    print("struct Cp932EncodeEntry { char16_t unicode; std::uint16_t code; };")
    print(f"constexpr Cp932EncodeEntry CP932_ENCODE[{len(items)}] = {{")
    for i in range(0, len(items), 6):
        print("    " + ", ".join(f"{{0x{u:04X}, 0x{c:04X}}}" for u, c in items[i:i + 6]) + ",")
    print("};")

    sys.stderr.write(f"decode entries mapped: {sum(1 for v in decode if v)} / {len(decode)}; encode entries: {len(items)}\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
